CREATE TABLE IF NOT EXISTS MAINTENANCE_APPOINTMENT (
  MAPIdAppointment INT NOT NULL AUTO_INCREMENT,
  MOIdMoto INT NOT NULL,
  MAIdAgencie INT NOT NULL,
  MAIdSchedule INT NOT NULL,
  MAPDate DATE NOT NULL,
  MAPObservations VARCHAR(500) NULL,
  MAPStatus ENUM('PROGRAMADO') NOT NULL DEFAULT 'PROGRAMADO',
  MAPCreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (MAPIdAppointment),
  UNIQUE KEY UQ_MaintenanceAppointment_Slot (MAIdAgencie, MAPDate, MAIdSchedule),
  KEY IX_MaintenanceAppointment_Motorcycle (MOIdMoto, MAPDate),
  CONSTRAINT FK_MaintenanceAppointment_Motorcycle
    FOREIGN KEY (MOIdMoto) REFERENCES MOTORCYCLES (MOIdMoto)
    ON DELETE NO ACTION ON UPDATE NO ACTION,
  CONSTRAINT FK_MaintenanceAppointment_Agency
    FOREIGN KEY (MAIdAgencie) REFERENCES AGENCIES (AGIdAgencie)
    ON DELETE NO ACTION ON UPDATE NO ACTION,
  CONSTRAINT FK_MaintenanceAppointment_Schedule
    FOREIGN KEY (MAIdSchedule) REFERENCES SCHEDULES (SCIdSchedule)
    ON DELETE NO ACTION ON UPDATE NO ACTION
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
