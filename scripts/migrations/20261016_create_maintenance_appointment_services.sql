CREATE TABLE IF NOT EXISTS MAINTENANCE_APPOINTMENT_SERVICE (
  MAPIdAppointment INT NOT NULL,
  SEIdService INT NOT NULL,
  PRIMARY KEY (MAPIdAppointment, SEIdService),
  CONSTRAINT FK_AppointmentService_Appointment
    FOREIGN KEY (MAPIdAppointment) REFERENCES MAINTENANCE_APPOINTMENT (MAPIdAppointment)
    ON DELETE CASCADE ON UPDATE NO ACTION,
  CONSTRAINT FK_AppointmentService_Service
    FOREIGN KEY (SEIdService) REFERENCES SERVICES (SEIdService)
    ON DELETE NO ACTION ON UPDATE NO ACTION
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
